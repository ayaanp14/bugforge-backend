/**
 * Prints the SPA's copy of the plan catalogue — frontend
 * src/content/plans.generated.ts — from lib/plans.ts.
 *
 *   npx tsx scripts/plans-manifest.ts > ../frontend/src/content/plans.generated.ts
 *
 * Why the SPA holds a copy (the owner's call, 2026-10-15): the pricing page
 * has to be drawn before the API answers — in full on its first frame, by
 * the static-first view the build writes into /pricing (lib/seo/views), and
 * in the HTML Google reads — and it used to wait for GET /api/billing/plans
 * to show a single price. The numbers stay owned here: checkout prices an
 * order from lib/plans and never from the browser, and every limit is
 * enforced by services/entitlements. The copy is generated so the page can
 * never quote a price the checkout does not charge; rerun this after any
 * change to lib/plans.ts. The SPA's words around the numbers (taglines,
 * feature rows, the FAQ) are in frontend src/content/plans.ts.
 */
import {
  ACTION_LABELS,
  CREDIT_COSTS,
  CREDIT_PACKS,
  FREE_PLAN,
  METERED_ACTIONS,
  PLAN_OFFERS,
  allowanceLabel,
  planFor,
} from "../src/lib/plans.js";

const plan = (id: "free" | "pro" | "max") => {
  const p = id === "free" ? FREE_PLAN : planFor(id);
  const e = p.entitlements;
  return {
    id: p.id,
    name: p.name,
    tagline: p.tagline,
    allowances: Object.fromEntries(METERED_ACTIONS.map((a) => [a, { ...e.allowances[a], label: allowanceLabel(e.allowances[a]) }])),
    skillTestLevels: e.skillTestLevels,
    resumeExport: e.resumeExport,
    resumeOptimize: e.resumeOptimize,
    voiceDurationsMin: e.voiceDurationsMin,
  };
};

const catalogue = {
  plans: { free: plan("free"), pro: plan("pro"), max: plan("max") },
  offers: PLAN_OFFERS,
  creditPacks: CREDIT_PACKS,
  creditCosts: CREDIT_COSTS,
  actions: METERED_ACTIONS.map((id) => ({ id, ...ACTION_LABELS[id] })),
};

const json = JSON.stringify(catalogue, null, 2);

process.stdout.write(`/**
 * GENERATED by backend/scripts/plans-manifest.ts from backend/src/lib/plans.ts
 * — do not edit; rerun it after changing the plan table:
 *
 *   cd backend && npx tsx scripts/plans-manifest.ts > ../frontend/src/content/plans.generated.ts
 *
 * The numbers the pricing page draws (prices, allowances, credit costs).
 * The API owns them — it prices every checkout and enforces every limit —
 * and this copy lets the page paint them without asking it first. Plain
 * data, no imports: the static view, the Worker and the build read it.
 */

export const PLAN_CATALOGUE = ${json} as const;
`);
