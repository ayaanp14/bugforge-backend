"use strict";
const input = require("fs").readFileSync(0, "utf8");
const config = JSON.parse(input);
const opts = config.compilerOptions ?? {};
const findings = [];
const level = (sev, msg) => findings.push(`${sev}: ${msg}`);
if (opts.strict !== true) level("error", "strict is off - enable it (implies noImplicitAny, strictNullChecks, strictFunctionTypes, useUnknownInCatchVariables)");
if (opts.noUncheckedIndexedAccess !== true) level("recommend", "noUncheckedIndexedAccess: arr[i] becomes T | undefined and catches the most common crash");
if (opts.skipLibCheck !== true) level("recommend", "skipLibCheck: do not re-check node_modules declaration files");
if (opts.isolatedModules !== true) level("recommend", "isolatedModules: required for esbuild/swc/tsx style transpilers");
const targetYear = /^es(\d{4})$/i.exec(String(opts.target ?? "es5"))?.[1];
if (!opts.target) level("warn", "no target - defaults to ES5 and downlevels everything");
else if (/^es(3|5|6|2015|2016|2017|2018|2019)$/i.test(opts.target)) level("warn", `target ${opts.target} is older than the runtime supports - Node 16 runs ES2021`);
const mod = String(opts.module ?? "").toLowerCase(), res = String(opts.moduleResolution ?? "").toLowerCase();
if ((mod === "nodenext" || mod === "node16") !== (res === "nodenext" || res === "node16") && mod && res) level("warn", `module ${opts.module} and moduleResolution ${opts.moduleResolution} disagree`);
if (mod === "commonjs" && opts.esModuleInterop !== true) level("warn", "commonjs without esModuleInterop: default imports from CJS packages misbehave");
if (!config.include && !config.files) level("warn", "no include/files - every .ts under the folder is compiled, node_modules aside");
if (opts.outDir && !opts.rootDir) level("recommend", "set rootDir alongside outDir so the output layout is predictable");
if (opts.noEmit === true && opts.outDir) level("info", "noEmit with outDir: this config only type-checks; another tool emits");
console.log(`tsconfig: ${findings.length} finding(s)`);
for (const f of findings) console.log(`- ${f}`);
if (!findings.length) console.log("- looks good");
