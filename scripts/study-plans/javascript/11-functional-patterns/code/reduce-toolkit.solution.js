"use strict";
const lines = require("fs").readFileSync(0, "utf8").split("\n").filter((l) => l.trim() !== "");
const map = (f, xs) => xs.reduce((acc, x) => (acc.push(f(x)), acc), []);
const filter = (p, xs) => xs.reduce((acc, x) => (p(x) && acc.push(x), acc), []);
const flatMap = (f, xs) => xs.reduce((acc, x) => (acc.push(...f(x)), acc), []);
const groupBy = (key, xs) => xs.reduce((acc, x) => { (acc[key(x)] ??= []).push(x); return acc; }, {});
const partition = (p, xs) => xs.reduce(([yes, no], x) => (p(x) ? yes.push(x) : no.push(x), [yes, no]), [[], []]);
const zip = (xs, ys) => xs.reduce((acc, x, i) => (i < ys.length && acc.push([x, ys[i]]), acc), []);
const unique = (xs) => [...xs.reduce((set, x) => set.add(x), new Set())];
const countBy = (key, xs) => xs.reduce((m, x) => m.set(key(x), (m.get(key(x)) ?? 0) + 1), new Map());
const nums = lines[0].trim().split(/\s+/).map(Number);
console.log(`map=${JSON.stringify(map((x) => x * x, nums))}`);
console.log(`filter=${JSON.stringify(filter((x) => x % 2 === 0, nums))}`);
console.log(`flatMap=${JSON.stringify(flatMap((x) => (x > 0 ? [x, -x] : []), nums))}`);
console.log(`groupBy=${JSON.stringify(groupBy((x) => (x % 2 ? "odd" : "even"), nums))}`);
console.log(`partition=${JSON.stringify(partition((x) => x >= 5, nums))}`);
console.log(`zip=${JSON.stringify(zip(nums, ["a", "b", "c"]))}`);
console.log(`unique=${JSON.stringify(unique(nums))}`);
console.log(`countBy=${JSON.stringify([...countBy((x) => x % 3, nums)].sort(([a], [b]) => a - b))}`);
console.log(`sum=${nums.reduce((a, b) => a + b, 0)} max=${nums.reduce((m, x) => Math.max(m, x), -Infinity)}`);
