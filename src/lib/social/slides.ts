/**
 * The day's image slides, as data — pure, pinned by social.test.ts. The
 * routes draw them as PNGs (lib/social/slide-card.ts) in each platform's
 * size, and bundle them into a PDF for LinkedIn's document carousel.
 *
 * Who writes what is the point: the model writes the cover's hook and the
 * takeaway (`SocialCopy`), and every fact a slide states — the statement,
 * the example, the options, the answer, the approach, the complexity, the
 * company — is quoted from the catalogue item. A carousel stating the wrong
 * answer to an aptitude question under the CodeKairo logo is the one
 * failure this module cannot afford, and a model asked to restate a worked
 * solution will sometimes restate it wrong.
 *
 * Drawn rather than generated by an image model: an image model cannot be
 * trusted to spell a constraint or an option, and would not draw in the
 * site's design. satori draws exact text in Gilroy on the blue scale, in
 * any size, on the box's own CPU.
 */

import type { Item } from "./item.js";

export interface SocialCopy {
  hook: string;
  sub: string;
  points: string[];
  takeaway: string;
  altText: string;
}

export type Slide =
  | { kind: "cover"; eyebrow: string; title: string; sub: string; chips: string[] }
  | { kind: "text"; eyebrow: string; title: string; body: string }
  | { kind: "code"; eyebrow: string; title: string; code: string }
  /** `numbered` for steps; a plain list (facts, contents) gets bullets. */
  | { kind: "list"; eyebrow: string; title: string; items: string[]; numbered: boolean }
  | { kind: "options"; eyebrow: string; title: string; options: string[] }
  | { kind: "answer"; eyebrow: string; title: string; answer: string; steps: string[] }
  | { kind: "cta"; eyebrow: string; title: string; sub: string; url: string };

const LETTERS = "ABCDEFGH";

/** A slide holds a paragraph, not an article: cut at a sentence when the source runs long. */
export function clip(s: string, max: number): string {
  const t = s.trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max);
  const stop = Math.max(cut.lastIndexOf(". "), cut.lastIndexOf(".\n"));
  return stop > max * 0.5 ? cut.slice(0, stop + 1) : `${cut.replace(/\s+\S*$/, "")}…`;
}

const clipLines = (s: string, maxLines: number, maxWidth: number) =>
  s
    .split("\n")
    .slice(0, maxLines)
    .map((l) => (l.length > maxWidth ? `${l.slice(0, maxWidth - 1)}…` : l))
    .join("\n");

const short = (list: string[] | undefined, n: number, max: number) => (list ?? []).filter(Boolean).slice(0, n).map((s) => clip(s, max));

const chipsOf = (item: Item) => [item.difficulty, ...(item.topics ?? []).slice(0, 2)].filter((s): s is string => Boolean(s));

const cta = (item: Item, copy: SocialCopy, verb: string): Slide => ({
  kind: "cta",
  eyebrow: "Practise it free",
  title: copy.takeaway || verb,
  sub: verb,
  url: `codekairo.com${item.path}`,
});

export function slidesFor(item: Item, copy: SocialCopy): Slide[] {
  const out: Slide[] = [];
  const cover = (eyebrow: string, chips = chipsOf(item)): Slide => ({ kind: "cover", eyebrow, title: copy.hook || item.title, sub: copy.sub, chips });

  switch (item.theme) {
    case "company-dsa": {
      out.push(cover(item.company ? `Asked at ${item.company}` : "Interview problem"));
      if (item.statement) out.push({ kind: "text", eyebrow: item.title, title: "The problem", body: clip(item.statement, 420) });
      if (item.example) out.push({ kind: "code", eyebrow: item.title, title: "Example", code: clipLines(item.example, 8, 46) });
      if (item.hints?.length) out.push({ kind: "text", eyebrow: "Think first", title: "Hint", body: clip(item.hints[0], 260) });
      if (item.idea) out.push({ kind: "text", eyebrow: "The key idea", title: "How to see it", body: clip(item.idea, 320) });
      if (item.steps?.length) out.push({ kind: "list", eyebrow: "Approach", title: "Step by step", items: short(item.steps, 4, 140), numbered: true });
      const facts = [
        item.complexity?.time ? `Time: ${item.complexity.time}` : "",
        item.complexity?.space ? `Space: ${item.complexity.space}` : "",
        ...short(item.pitfalls, 2, 130).map((p) => `Pitfall: ${p}`),
      ].filter(Boolean);
      if (facts.length) out.push({ kind: "list", eyebrow: "Before you submit", title: "Complexity and traps", items: facts, numbered: false });
      const others = (item.companies ?? []).filter((c) => c !== item.company).slice(0, 6);
      if (others.length) out.push({ kind: "text", eyebrow: "Also tagged", title: "Where else it comes up", body: others.join(" · ") });
      out.push(cta(item, copy, "Solve it in 13 languages on CodeKairo"));
      break;
    }
    case "aptitude": {
      out.push(cover(item.topics?.[0] ? `Aptitude · ${item.topics[0]}` : "Aptitude"));
      out.push({
        kind: "options",
        eyebrow: item.seconds ? `Target: ${item.seconds} seconds` : "Your turn",
        title: clip(item.question ?? "", 300),
        options: (item.options ?? []).map((o, i) => `${LETTERS[i]}  ${o}`),
      });
      out.push({ kind: "text", eyebrow: "Pause", title: "Got your answer?", body: "Comment the letter first. The answer and the worked solution are on the next slide." });
      const answer = item.answer !== undefined && item.options?.[item.answer] !== undefined ? `${LETTERS[item.answer]} · ${item.options[item.answer]}` : "";
      out.push({ kind: "answer", eyebrow: "Answer", title: "Worked solution", answer, steps: short(item.solution, 4, 120) });
      if (item.approach) out.push({ kind: "text", eyebrow: "The shortcut", title: "Remember this", body: clip(item.approach, 340) });
      out.push(cta(item, copy, "More questions like this on CodeKairo"));
      break;
    }
    case "concept":
    case "cs-fundamentals": {
      out.push(cover(item.theme === "concept" ? "DSA roadmap" : item.topics?.[0] ? `Interview · ${item.topics[0]}` : "CS fundamentals"));
      const faq = item.faq ?? [];
      out.push({ kind: "text", eyebrow: item.title, title: faq[0]?.q ? clip(faq[0].q, 90) : "In one paragraph", body: clip(item.summary ?? "", 420) });
      for (const f of faq.slice(1, 3)) out.push({ kind: "text", eyebrow: "Interview question", title: clip(f.q, 90), body: clip(f.a, 380) });
      if (item.sections?.length) out.push({ kind: "list", eyebrow: "The full guide covers", title: "What to learn next", items: short(item.sections, 5, 70), numbered: false });
      out.push(cta(item, copy, item.theme === "concept" ? "Read the tutorial and practise on CodeKairo" : "Read the full notes on CodeKairo"));
      break;
    }
    case "sql": {
      out.push(cover("SQL interview problem"));
      if (item.statement) out.push({ kind: "text", eyebrow: item.title, title: "The task", body: clip(item.statement, 420) });
      if (item.tables) out.push({ kind: "code", eyebrow: item.title, title: "Tables", code: clipLines(item.tables, 12, 46) });
      if (copy.points.length) out.push({ kind: "list", eyebrow: "Think about", title: "Before you write the query", items: short(copy.points, 3, 140), numbered: true });
      out.push(cta(item, copy, "Write the query in MySQL on CodeKairo"));
      break;
    }
    case "motivation": {
      out.push(cover("For your prep", []));
      for (const p of copy.points.slice(0, 5)) out.push({ kind: "text", eyebrow: "", title: "", body: clip(p, 220) });
      out.push(cta(item, copy, "One step today: start the DSA roadmap"));
      break;
    }
    case "product": {
      out.push(cover(item.feature?.name ?? "CodeKairo", []));
      if (item.feature) out.push({ kind: "text", eyebrow: "What it is", title: item.feature.name, body: clip(item.feature.summary, 380) });
      if (copy.points.length) out.push({ kind: "list", eyebrow: "What you can do", title: "With it, you can", items: short(copy.points, 4, 140), numbered: false });
      // Not "free": some features (mock interviews, bug hunts) have plan limits.
      out.push(cta(item, copy, "Try it on CodeKairo"));
      break;
    }
  }
  return out;
}
